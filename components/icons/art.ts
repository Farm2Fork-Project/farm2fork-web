const circle = (cx: number, cy: number, r: number) =>
  `M${cx - r} ${cy}a${r} ${r} 0 1 0 ${2 * r} 0a${r} ${r} 0 1 0 ${-2 * r} 0Z`;

const dot = (x: number, y: number) => `M${x} ${y}h.01`;

/** Alternating-radius polygon: a stamped seal / star once the joins are rounded. */
const burst = (cx: number, cy: number, outer: number, inner: number, points: number) => {
  const steps = points * 2;
  const coords = Array.from({ length: steps }, (_, i) => {
    const radius = i % 2 === 0 ? outer : inner;
    const angle = (Math.PI * 2 * i) / steps - Math.PI / 2;
    return `${(cx + radius * Math.cos(angle)).toFixed(2)} ${(cy + radius * Math.sin(angle)).toFixed(2)}`;
  });
  return `M${coords.join("L")}Z`;
};

