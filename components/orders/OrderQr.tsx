"use client";
import { useEffect, useMemo, useRef, useState } from "react";
import { useLanguage } from "../LanguageContext";
import { ApiClient } from "@/lib/api/client";
import { ApiError } from "@/lib/api/contracts";
import { loginPathFor } from "@/lib/auth/role-routes";
import {
  TraceRepository,
  type OrderQr as QrData,
} from "@/lib/trace/trace-repository";

export function OrderQr({
  orderId,
  eligible,
}: {
  orderId: string;
  eligible: boolean;
}) {
  const { language } = useLanguage();
  const copy = (en: string, ur: string) => (language === "ur" ? ur : en);
  const [open, setOpen] = useState(false);
  if (!eligible) return null;
  return (
    <>
      <button
        type="button"
        className="btn btn-outline"
        onClick={() => setOpen(true)}
      >
        {copy("Order QR label", "آرڈر کا کیو آر لیبل")}
      </button>
      {open ? (
        <QrPanel key={orderId} orderId={orderId} close={() => setOpen(false)} />
      ) : null}
    </>
  );
}
function QrPanel({ orderId, close }: { orderId: string; close: () => void }) {
  const { language } = useLanguage();
  const copy = (en: string, ur: string) => (language === "ur" ? ur : en);
  const dialog = useRef<HTMLDialogElement>(null);
  const repository = useMemo(
    () => new TraceRepository({ client: new ApiClient() }),
    [],
  );
  const [data, setData] = useState<QrData>();
  const [error, setError] = useState<number | undefined>();
  const [attempt, setAttempt] = useState(0);
  const [notice, setNotice] = useState("");
  useEffect(() => {
    dialog.current?.showModal();
  }, []);
  useEffect(() => {
    let active = true;
    void repository.getOrderQr(orderId).then(
      (value) => {
        if (active) setData(value);
      },
      (error) => {
        if (active) setError(error instanceof ApiError ? error.status : 0);
      },
    );
    return () => {
      active = false;
    };
  }, [orderId, repository, attempt]);
  const share = async (native: boolean) => {
    if (!data) return;
    try {
      if (native && navigator.share)
        await navigator.share({ title: "Farm2Fork", url: data.qrCode });
      else {
        await navigator.clipboard.writeText(data.qrCode);
        setNotice(copy("Link copied", "لنک کاپی ہو گیا"));
      }
    } catch {
      setNotice(
        copy(
          "Could not share. Select and copy the link below.",
          "شیئر نہیں ہو سکا۔ نیچے دیا گیا لنک منتخب کر کے کاپی کریں۔",
        ),
      );
    }
  };
  const print = () => {
    if (!data) return;
    const label = window.open("", "_blank", "width=500,height=600");
    if (!label) {
      setNotice(
        copy(
          "Allow popups to print this label.",
          "لیبل پرنٹ کرنے کے لیے پاپ اپ کی اجازت دیں۔",
        ),
      );
      return;
    }
    label.opener = null;
    label.document.title = "Farm2Fork QR label";
    const heading = label.document.createElement("h1");
    heading.textContent = "Farm2Fork";
    const image = label.document.createElement("img");
    image.alt = "Order QR";
    image.width = 280;
    image.height = 280;
    const link = label.document.createElement("p");
    link.textContent = data.qrCode;
    link.style.overflowWrap = "anywhere";
    label.document.body.append(heading, image, link);
    image.onload = () => {
      label.focus();
      label.print();
    };
    image.src = data.qrImageDataUri;
  };
  return (
    <dialog
      ref={dialog}
      className="order-qr-dialog"
      aria-labelledby="order-qr-title"
      onCancel={close}
      onClose={close}
      dir={language === "ur" ? "rtl" : "ltr"}
    >
      <div className="order-qr-head">
        <h2 id="order-qr-title">
          {copy("Order QR label", "آرڈر کا کیو آر لیبل")}
        </h2>
        <button type="button" className="btn btn-outline" onClick={close}>
          {copy("Close", "بند کریں")}
        </button>
      </div>
      <p>
        {copy(
          "Share the public journey. Private order details require sign-in.",
          "عوامی سفر شیئر کریں۔ نجی آرڈر کی تفصیلات کے لیے لاگ ان ضروری ہے۔",
        )}
      </p>
      {data ? (
        <>
          {/* PNG data URI is generated by the authenticated backend. */}
          {/* eslint-disable-next-line @next/next/no-img-element */}
          <img
            className="order-qr-image"
            src={data.qrImageDataUri}
            width={280}
            height={280}
            alt={copy(
              "Scan to view this order’s journey",
              "آرڈر کا سفر دیکھنے کے لیے اسکین کریں",
            )}
          />
          <p className="order-qr-url" dir="ltr">
            {data.qrCode}
          </p>
          <div className="order-qr-actions">
            <a className="btn btn-primary" href={data.qrCode}>
              {copy("View journey", "سفر دیکھیں")}
            </a>
            <button
              className="btn btn-outline"
              onClick={() => void share(false)}
            >
              {copy("Copy link", "لنک کاپی کریں")}
            </button>
            <button
              className="btn btn-outline"
              onClick={() => void share(true)}
            >
              {copy("Share link", "لنک شیئر کریں")}
            </button>
            <a
              className="btn btn-outline"
              href={data.qrImageDataUri}
              download={`farm2fork-order-${orderId}.png`}
            >
              {copy("Download PNG", "پی این جی ڈاؤن لوڈ کریں")}
            </a>
            <button className="btn btn-outline" onClick={print}>
              {copy("Print label", "لیبل پرنٹ کریں")}
            </button>
          </div>
        </>
      ) : error !== undefined ? (
        <div role="alert">
          <p>
            {copy(
              "QR unavailable. Refresh payment status or try again.",
              "کیو آر دستیاب نہیں۔ ادائیگی کی حالت تازہ کریں یا دوبارہ کوشش کریں۔",
            )}
          </p>
          <button
            className="btn btn-outline"
            onClick={() => {
              setError(undefined);
              setAttempt((value) => value + 1);
            }}
          >
            {copy("Retry", "دوبارہ کوشش کریں")}
          </button>
          {error === 401 ? (
            <a
              className="btn btn-primary"
              href={loginPathFor(`/orders/${orderId}`)}
            >
              {copy("Sign in", "لاگ ان کریں")}
            </a>
          ) : null}
        </div>
      ) : (
        <p role="status">{copy("Loading QR…", "کیو آر لوڈ ہو رہا ہے…")}</p>
      )}
      <p role="status">{notice}</p>
    </dialog>
  );
}
